// O12: the release obligation, STATED in the obligation channel.
//
// At every `locks L { … }` exit the lock invariant of `L` must hold again.
// No checker rule refuses a locked section whose callees cannot re-establish
// it from what they PROMISE (their `ensures`), so such a section is
// checker-clean and still leaves premise (b) of the goal theorem
// (`NutzerPflicht`) unproved. What follows states that gap per locked
// section -- in this obligation channel, never as a diagnostic: the checker
// verdict of the file is unchanged by this section.
//
// The check is SYNTACTIC and deliberately one-sided. It collects the slot
// cells (`T.slots[i].f`, index included) the invariant reads and the cells
// the section's UNCONDITIONAL direct callees promise in their `ensures`
// (current-state reads only -- `old(..)` speaks about the entry state and
// promises nothing about the release state). Conditional, indirect and
// ambiguous calls are never counted as promises. So the verdicts read:
//
// * `RELEASE HOLDS (syntactic)` -- every invariant cell is promised, with
//   no uncounted call in the section. This is NOT a proof (transitive
//   promises, arithmetic and aliasing are all beyond this text), only the
//   absence of a syntactic gap.
// * `RELEASE UNPROVED` -- the exact gap: invariant cells no callee
//   promises, and/or calls whose promise cannot be counted. This names
//   where the user's proof (or a stronger callee contract) must go.
//
// A missed form stays on the obliging side: an unknown expression shape
// contributes no promised cell, an unknown statement shape contributes no
// unconditional call. The section may oblige, it may not acquit.
//
// NOTE (duplication): the same analysis stands in `gegenbeispiel.rs`. It is
// duplicated, not shared, so that neither subcommand grows a dependency on
// a checker pass or on `lean_g.rs` -- both of which are owned by other
// lanes. If the wording moves, move it in both files.

/// An index as the cell name carries it: a literal by value, a bare name by
/// name, anything else as `[…]`. (`Ort::text` renders every index as `[…]`,
/// which would merge `konto.slots[0].stand` and `konto.slots[1].stand` into
/// one cell -- exactly the distinction O12 is about.)
fn index_text(e: &Expr) -> String {
    match &e.art {
        ExprArt::Zahl(n) => format!("[{n}]"),
        ExprArt::Ort(o) if o.suffixe.is_empty() => format!("[{}]", o.basis.text),
        _ => "[…]".to_string(),
    }
}

/// A place as the cell name carries it: like `Ort::text`, but with the
/// index spelled out (see `index_text`).
fn ort_mit_index(o: &Ort) -> String {
    let mut s = o.basis.text.clone();
    for suf in &o.suffixe {
        match suf {
            OrtSuffix::Feld(i) => {
                s.push('.');
                s.push_str(&i.text);
            }
            OrtSuffix::Ueber(i) => {
                s.push_str("->");
                s.push_str(&i.text);
            }
            OrtSuffix::Index(e) => s.push_str(&index_text(e)),
        }
    }
    s
}

/// A slot read `T.slots[i].f`, rendered with its index -- or `None` for any
/// other place.
fn als_schlitz(o: &Ort) -> Option<String> {
    match o.suffixe.as_slice() {
        [OrtSuffix::Feld(slots), OrtSuffix::Index(_), OrtSuffix::Feld(_)]
            if slots.text == "slots" =>
        {
            Some(ort_mit_index(o))
        }
        _ => None,
    }
}

/// Slot cells read by an expression (see the module note: no `old`).
fn zellen_expr(e: &Expr, acc: &mut BTreeSet<String>) {
    match &e.art {
        ExprArt::Ort(o) => {
            if let Some(z) = als_schlitz(o) {
                acc.insert(z);
            }
        }
        ExprArt::Alt(_) => {}
        ExprArt::Klammer(x) => zellen_expr(x, acc),
        ExprArt::Unaer(_, x) => zellen_expr(x, acc),
        ExprArt::Binaer(_, a, b) => {
            zellen_expr(a, acc);
            zellen_expr(b, acc);
        }
        ExprArt::Ruf(r) => {
            for a in &r.argumente {
                zellen_expr(a, acc);
            }
        }
        ExprArt::Eingebaut(b) => match &**b {
            Eingebaut::Sizeof(TypOderOrt::Ort(o)) | Eingebaut::Lenof(TypOderOrt::Ort(o)) => {
                if let Some(z) = als_schlitz(o) {
                    acc.insert(z);
                }
            }
            Eingebaut::Aligned(a, b) => {
                zellen_expr(a, acc);
                zellen_expr(b, acc);
            }
            _ => {}
        },
        ExprArt::Zaehle { rumpf, .. } => zellen_pred(rumpf, acc),
        ExprArt::ArrayLit(es) => {
            for x in es {
                zellen_expr(x, acc);
            }
        }
        _ => {}
    }
}

/// Slot cells read by a contract predicate (see the module note).
fn zellen_pred(p: &Pred, acc: &mut BTreeSet<String>) {
    match &p.art {
        PredArt::Vergleich(e) => zellen_expr(e, acc),
        PredArt::Quantor(q) => zellen_pred(&q.rumpf, acc),
        PredArt::Element(e, _) => zellen_expr(e, acc),
        PredArt::Erreicht { von, nach, .. } => {
            for o in [von, nach] {
                if let Some(z) = als_schlitz(o) {
                    acc.insert(z);
                }
            }
        }
        PredArt::Held { .. } => {}
        PredArt::Klammer(q) => zellen_pred(q, acc),
        PredArt::Nicht(q) => zellen_pred(q, acc),
        PredArt::Und(a, b) | PredArt::Oder(a, b) | PredArt::Folgt(a, b) => {
            zellen_pred(a, acc);
            zellen_pred(b, acc);
        }
    }
}

/// What a call in a locked section resolves to: a direct callee by short
/// name, an indirect call (a place, not a name), or no call at all (a
/// `P(a: 1)` value construction, which parses as a `Ruf` with marks).
enum RufZiel {
    Direkt(String),
    Indirekt,
    KeinRuf,
}

fn ruf_ziel(r: &Ruf) -> RufZiel {
    if r.ist_verbundwert() {
        return RufZiel::KeinRuf;
    }
    match r.path() {
        Some(p) => match p.teile.last() {
            Some(l) => RufZiel::Direkt(l.text.clone()),
            None => RufZiel::Indirekt,
        },
        None => RufZiel::Indirekt,
    }
}

/// One locked section: the lock (short name) and its calls. `sicher` holds
/// the unconditional direct callees (the only ones counted as promises);
/// `unsicher` counts the calls that are conditional, indirect or otherwise
/// unresolvable (never counted -- see the module note).
struct Abschnitt {
    sperre: String,
    sicher: Vec<String>,
    unsicher: Vec<String>,
}

/// Unconditional calls of a block: straight-line statements only. Anything
/// under a branch, a loop, a `narrow` or a `let … else` is conditional and
/// goes to `unsicher` with its reason.
fn rufe_in_block(b: &Block, sicher: &mut Vec<String>, unsicher: &mut Vec<String>) {
    for s in &b.anweisungen {
        match &s.art {
            StmtArt::Ruf(r) => match ruf_ziel(r) {
                RufZiel::Direkt(n) => sicher.push(n),
                RufZiel::Indirekt => unsicher.push("indirect call".to_string()),
                RufZiel::KeinRuf => {}
            },
            StmtArt::Let(l) => {
                if let ExprArt::Ruf(r) = &l.wert.art {
                    match ruf_ziel(r) {
                        RufZiel::Direkt(n) => sicher.push(n),
                        RufZiel::Indirekt => unsicher.push("indirect call".to_string()),
                        RufZiel::KeinRuf => {}
                    }
                }
            }
            StmtArt::Sperrt(sp) => rufe_in_block(&sp.rumpf, sicher, unsicher),
            _ => rufe_bedingt(&s.art, unsicher),
        }
    }
}

/// Calls under a branch, a loop, a `narrow` or a `let … else`: present but
/// conditional, so never promises. Their names are recorded for the report.
fn rufe_bedingt(art: &StmtArt, unsicher: &mut Vec<String>) {
    match art {
        StmtArt::Wenn(w) => {
            for (_, b) in &w.zweige {
                rufe_in_block_bedingt(b, unsicher);
            }
            if let Some(s) = &w.sonst {
                rufe_in_block_bedingt(s, unsicher);
            }
        }
        StmtArt::Schleife(sl) => match &**sl {
            Schleife::Traverse(t) => rufe_in_block_bedingt(&t.rumpf, unsicher),
            Schleife::Retry(r) => rufe_in_block_bedingt(&r.rumpf, unsicher),
            Schleife::Forever(f) => rufe_in_block_bedingt(&f.rumpf, unsicher),
        },
        StmtArt::Bricht(br) => rufe_in_block_bedingt(&br.rumpf, unsicher),
        StmtArt::Match(m) => {
            for z in &m.zweige {
                rufe_in_block_bedingt(&z.rumpf, unsicher);
            }
        }
        StmtArt::Narrow(n) => rufe_in_block_bedingt(&n.sonst, unsicher),
        StmtArt::LetSonst(l) => {
            if let LetQuelle::Ruf(r) = &l.quelle {
                match ruf_ziel(r) {
                    RufZiel::Direkt(n) => {
                        unsicher.push(format!("conditional call of {n} (`let … else`)"));
                    }
                    RufZiel::Indirekt => unsicher.push("conditional indirect call".to_string()),
                    RufZiel::KeinRuf => {}
                }
            }
            rufe_in_block_bedingt(&l.sonst, unsicher);
        }
        _ => {}
    }
}

/// Every call under a conditional, by short name where known.
fn rufe_in_block_bedingt(b: &Block, unsicher: &mut Vec<String>) {
    for s in &b.anweisungen {
        match &s.art {
            StmtArt::Ruf(r) => match ruf_ziel(r) {
                RufZiel::Direkt(n) => unsicher.push(format!("conditional call of {n}")),
                RufZiel::Indirekt => unsicher.push("conditional indirect call".to_string()),
                RufZiel::KeinRuf => {}
            },
            StmtArt::Let(l) => {
                if let ExprArt::Ruf(r) = &l.wert.art {
                    match ruf_ziel(r) {
                        RufZiel::Direkt(n) => {
                            unsicher.push(format!("conditional call of {n}"));
                        }
                        RufZiel::Indirekt => {
                            unsicher.push("conditional indirect call".to_string());
                        }
                        RufZiel::KeinRuf => {}
                    }
                }
            }
            _ => rufe_bedingt(&s.art, unsicher),
        }
    }
}

/// Every `locks L { … }` section of a body, with a nested section getting
/// its own row.
fn sperr_abschnitte(b: &Block, acc: &mut Vec<Abschnitt>) {
    for s in &b.anweisungen {
        match &s.art {
            StmtArt::Sperrt(sp) => {
                let mut sicher = Vec::new();
                let mut unsicher = Vec::new();
                rufe_in_block(&sp.rumpf, &mut sicher, &mut unsicher);
                acc.push(Abschnitt { sperre: sp.sperre.basis.text.clone(), sicher, unsicher });
                sperr_abschnitte(&sp.rumpf, acc);
            }
            StmtArt::Wenn(w) => {
                for (_, b) in &w.zweige {
                    sperr_abschnitte(b, acc);
                }
                if let Some(s) = &w.sonst {
                    sperr_abschnitte(s, acc);
                }
            }
            StmtArt::Schleife(sl) => match &**sl {
                Schleife::Traverse(t) => sperr_abschnitte(&t.rumpf, acc),
                Schleife::Retry(r) => sperr_abschnitte(&r.rumpf, acc),
                Schleife::Forever(f) => sperr_abschnitte(&f.rumpf, acc),
            },
            StmtArt::Bricht(br) => sperr_abschnitte(&br.rumpf, acc),
            StmtArt::Match(m) => {
                for z in &m.zweige {
                    sperr_abschnitte(&z.rumpf, acc);
                }
            }
            StmtArt::Narrow(n) => sperr_abschnitte(&n.sonst, acc),
            StmtArt::LetSonst(l) => sperr_abschnitte(&l.sonst, acc),
            _ => {}
        }
    }
}

fn sammle_funktionen<'a>(items: &'a [Item], fns: &mut Vec<&'a FnDecl>) {
    for item in items {
        match &item.art {
            ItemArt::Funktion(f) => fns.push(f),
            ItemArt::Modul(m) => sammle_funktionen(&m.items, fns),
            _ => {}
        }
    }
}

fn sammle_sperren<'a>(items: &'a [Item], sperren: &mut Vec<&'a LockDecl>) {
    for item in items {
        match &item.art {
            ItemArt::Lock(l) => sperren.push(l),
            ItemArt::Modul(m) => sammle_sperren(&m.items, sperren),
            _ => {}
        }
    }
}

fn menge_text(m: &BTreeSet<String>) -> String {
    if m.is_empty() {
        return "{}".to_string();
    }
    let mut v: Vec<&str> = m.iter().map(|s| s.as_str()).collect();
    v.sort();
    format!("{{{}}}", v.join(", "))
}

/// The O12 release-obligation section: one row per `locks L { … }` section,
/// as Lean comments (never a diagnostic -- the checker verdict stands).
pub(crate) fn freigabe_abschnitt(tree: &Programm) -> String {
    let mut out = String::new();
    out.push_str("-- RELEASE OBLIGATIONS (stated, not discharged -- O12).\n");
    out.push_str("--\n");
    out.push_str("-- At every `locks L { ... }` exit the lock invariant of `L` must hold\n");
    out.push_str("-- again, and it must follow from what the section's callees PROMISE\n");
    out.push_str("-- (their `ensures`), not from what their bodies happen to do. No checker\n");
    out.push_str("-- rule refuses a section whose callees cannot re-establish it, so such\n");
    out.push_str("-- a section is checker-clean and still leaves `NutzerPflicht` unproved.\n");
    out.push_str("-- Each row below is syntactic and one-sided (see the source of\n");
    out.push_str("-- `freigabe_abschnitt`): `RELEASE HOLDS (syntactic)` is not a proof,\n");
    out.push_str("-- while `RELEASE UNPROVED` names the exact gap.\n");
    let mut fns = Vec::new();
    sammle_funktionen(&tree.items, &mut fns);
    let mut sperren = Vec::new();
    sammle_sperren(&tree.items, &mut sperren);
    if sperren.iter().all(|l| l.invariante.is_none()) {
        out.push_str("-- No lock carries an invariant -- nothing is owed at any release.\n");
        return out;
    }
    // Promised cells per callee (short name); a short name declared twice
    // promises nothing countable -- guessing the body would wed the row to
    // the wrong contract.
    let mut versprechen: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let mut zweideutig: BTreeSet<String> = BTreeSet::new();
    for f in &fns {
        let mut zellen = BTreeSet::new();
        for e in &f.ensures {
            zellen_pred(e, &mut zellen);
        }
        if let Some(alt) = versprechen.get(&f.name.text) {
            if *alt != zellen {
                zweideutig.insert(f.name.text.clone());
            }
        } else {
            versprechen.insert(f.name.text.clone(), zellen);
        }
    }
    let mut zeilen = 0;
    for f in &fns {
        let FnRumpf::Block(b) = &f.rumpf else {
            continue;
        };
        let mut abschnitte = Vec::new();
        sperr_abschnitte(b, &mut abschnitte);
        for a in &abschnitte {
            zeilen += 1;
            // Same rule as for callees: a short lock name declared twice
            // resolves to nothing countable -- guessing the declaration
            // would wed the row to the wrong invariant.
            let treffer: Vec<&&LockDecl> =
                sperren.iter().filter(|l| l.name.text == a.sperre).collect();
            let [sperre] = treffer.as_slice() else {
                out.push_str(&format!(
                    "-- * {} locks `{}`: that lock is declared nowhere or ambiguously -- RELEASE UNPROVED (unknown lock).\n",
                    f.name.text, a.sperre
                ));
                continue;
            };
            let Some(inv) = &sperre.invariante else {
                out.push_str(&format!(
                    "-- * {} locks `{}`: no invariant -- nothing is owed at this release.\n",
                    f.name.text, a.sperre
                ));
                continue;
            };
            let mut braucht = BTreeSet::new();
            zellen_pred(inv, &mut braucht);
            if braucht.is_empty() {
                out.push_str(&format!(
                    "-- * {} locks `{}`: the invariant mentions no slot cell -- nothing countable is owed at this release.\n",
                    f.name.text, a.sperre
                ));
                continue;
            }
            let mut hat: BTreeSet<String> = BTreeSet::new();
            let mut unzaehlbar: Vec<String> = Vec::new();
            for n in &a.sicher {
                if zweideutig.contains(n) {
                    unzaehlbar.push(format!("ambiguous callee {n}"));
                } else if let Some(z) = versprechen.get(n) {
                    hat.extend(z.iter().cloned());
                } else {
                    unzaehlbar.push(format!("unknown callee {n}"));
                }
            }
            unzaehlbar.extend(a.unsicher.iter().cloned());
            let mut fehlt: Vec<&str> = braucht.iter().map(|s| s.as_str()).filter(|z| !hat.contains(*z)).collect();
            fehlt.sort();
            // Name every unconditional callee with what it promises, so the
            // row can be held against the callee contracts by hand.
            let mut rufer = Vec::new();
            for n in &a.sicher {
                match versprechen.get(n) {
                    Some(z) if !zweideutig.contains(n) => {
                        rufer.push(format!("{n} promises {}", menge_text(z)));
                    }
                    _ => rufer.push(format!("{n} promises nothing countable")),
                }
            }
            let ruf_text = if rufer.is_empty() { "no calls".to_string() } else { rufer.join("; ") };
            if fehlt.is_empty() && unzaehlbar.is_empty() {
                out.push_str(&format!(
                    "-- * {} locks `{}`: invariant over {}; {} -- RELEASE HOLDS (syntactic).\n",
                    f.name.text,
                    a.sperre,
                    menge_text(&braucht),
                    ruf_text
                ));
            } else {
                let mut gruende: Vec<String> = fehlt.iter().map(|z| format!("no callee promises {z}")).collect();
                gruende.extend(unzaehlbar);
                out.push_str(&format!(
                    "-- * {} locks `{}`: invariant over {}; {} -- RELEASE UNPROVED: {}.\n",
                    f.name.text,
                    a.sperre,
                    menge_text(&braucht),
                    ruf_text,
                    gruende.join("; ")
                ));
            }
        }
    }
    if zeilen == 0 {
        out.push_str("-- No `locks` section in any body -- nothing is owed at any release.\n");
    }
    out
}
