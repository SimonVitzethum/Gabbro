#[derive(Debug, Default)]
struct LeanFall {
    zeilen: Vec<(String, String)>,
}

impl LeanFall {
    fn feld(&self, k: &str) -> &str {
        self.zeilen
            .iter()
            .find(|(kk, _)| kk == k)
            .map(|(_, v)| v.as_str())
            .unwrap_or_else(|| panic!("no {k}"))
    }
    fn alle(&self, k: &str) -> Vec<&str> {
        self.zeilen
            .iter()
            .filter(|(kk, _)| kk == k)
            .map(|(_, v)| v.as_str())
            .collect()
    }
    fn wahr(&self, k: &str) -> bool {
        match self.feld(k) {
            "true" => true,
            "false" => false,
            x => panic!("{k}: {x}"),
        }
    }
}

fn faelle() -> Vec<(String, LeanFall)> {
    let mut out: Vec<(String, LeanFall)> = Vec::new();
    for zeile in LEAN_AUSGABE.lines() {
        if zeile.is_empty() || zeile == "ENDE" {
            continue;
        }
        let (k, v) = zeile.split_once(' ').unwrap_or((zeile, ""));
        if k == "FALL" {
            out.push((v.to_string(), LeanFall::default()));
        } else {
            out.last_mut()
                .expect("FALL first")
                .1
                .zeilen
                .push((k.to_string(), v.to_string()));
        }
    }
    out
}

fn zahlen(bs: impl IntoIterator<Item = u128>) -> String {
    bs.into_iter()
        .map(|b| b.to_string())
        .collect::<Vec<_>>()
        .join(",")
}

fn bytes_text(bs: &[u8]) -> String {
    zahlen(bs.iter().map(|&b| u128::from(b)))
}

fn abschnitt_text(s: &Abschnitt) -> String {
    format!(
        "{} {} {} {} {} {} {} {}",
        s.datei_off, s.datei_len, s.vaddr, s.mem_len, s.lesbar, s.schreibbar, s.ausfuehrbar, s.ausr
    )
}

