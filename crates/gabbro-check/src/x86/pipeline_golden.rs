/// Rust bytes, validator, reasons, entry, `bauOk` and image == Lean's.
#[test]
fn rust_pipeline_equals_lean_pipeline() {
    let lean = faelle();
    for (f, (name, l)) in alle_faelle().iter().zip(lean.iter()) {
        assert_eq!(f.name, name);
        let comp = compile(&f.cfg, &f.decl, &f.ps, &f.certs, &f.src);
        let comp_text = match &comp {
            Some(bs) => format!("SOME {}", bytes_text(bs)),
            None => "NONE".to_string(),
        };
        assert_eq!(comp_text, l.feld("COMPILE"), "{name}: compile");
        let bytes = comp.unwrap_or_default();
        assert_eq!(
            validate(&f.cfg, &f.decl, &f.ps, &f.certs, &f.src, &bytes),
            l.wahr("VALIDATE"),
            "{name}: validate"
        );
        let opt = optimise(&f.certs, &f.src);
        let gs = grund_liste(&opt);
        assert_eq!(
            zahlen(gs.iter().map(|&g| u128::from(g))),
            l.feld("GRUENDE"),
            "{name}: reasons"
        );
        let od = ohne_doppel(&gs);
        assert_eq!(
            zahlen(od.iter().map(|&g| u128::from(g))),
            l.feld("OHNEDOPPEL"),
            "{name}"
        );
        let pro = match &f.abi {
            Some(abi) => {
                let pro = encode_all(&prolog(&f.cfg, abi, f.ctx.len()));
                assert_eq!(bytes_text(&pro), l.feld("PROLOG"), "{name}: entry bytes");
                assert_eq!(
                    prolog_ok(&f.cfg, abi, f.ctx.len()),
                    l.wahr("PROLOGOK"),
                    "{name}"
                );
                pro
            }
            None => Vec::new(),
        };
        assert_eq!(
            bau_ok(f.profil, &f.cfg, &f.decl, &pro, &bytes, &od, &f.ps, &f.es),
            l.wahr("BAUOK"),
            "{name}: bauOk"
        );
        let bild = bild_fuer_p(
            &f.cfg, &f.decl, &pro, &f.certs, &f.src, &bytes, &f.ps, &f.welt, &f.es,
        )
        .unwrap_or_else(|| panic!("{name}: image"));
        assert_eq!(
            bytes_text(&bild.datei),
            l.feld("DATEI"),
            "{name}: file bytes"
        );
        let abschnitte: Vec<String> = bild.abschnitte.iter().map(abschnitt_text).collect();
        assert_eq!(abschnitte, l.alle("ABSCHNITT"), "{name}: sections");
        assert_eq!(
            zahlen(bild.eintraege.iter().copied()),
            l.feld("EINTRAEGE"),
            "{name}"
        );
        assert_eq!(l.feld("RELOKS"), "0");
        assert_eq!(l.feld("MODUS"), "fest");
    }
}

/// `compile_to_image` returns an image EXACTLY when Lean's chain passes,
/// and then Lean's `imageOk`/`weltOk` (`prologImageOk`) hold on it.
#[test]
fn compile_to_image_agrees_with_the_lean_verdicts() {
    let lean = faelle();
    let mut gebaut = 0;
    for (f, (name, l)) in alle_faelle().iter().zip(lean.iter()) {
        let p = Program {
            decl: f.decl.clone(),
            ctx: f.ctx.clone(),
            block: f.src.clone(),
            certs: Some(f.certs.clone()),
            placements: f.ps.clone(),
            welt: f.welt.clone(),
            extents: f.es.clone(),
            profil: f.profil,
            abi: f.abi.clone(),
        };
        let lean_kette = l.feld("COMPILE") != "NONE"
            && l.wahr("VALIDATE")
            && l.wahr("BAUOK")
            && (f.abi.is_none() || l.wahr("PROLOGOK"));
        match compile_to_image(&p, &f.cfg) {
            Ok(img) => {
                gebaut += 1;
                assert!(lean_kette, "{name}: Rust built what Lean's chain refuses");
                assert!(
                    l.wahr("IMAGEOK") && l.wahr("WELTOK"),
                    "{name}: Lean image check"
                );
                if f.abi.is_some() {
                    assert!(l.wahr("PROLOGIMAGEOK"), "{name}: Lean entry check");
                }
                assert_eq!(format!("SOME {}", bytes_text(&img.code)), l.feld("COMPILE"));
                assert_eq!(bytes_text(&img.bild.datei), l.feld("DATEI"), "{name}");
                let abschnitte: Vec<String> =
                    img.bild.abschnitte.iter().map(abschnitt_text).collect();
                assert_eq!(abschnitte, l.alle("ABSCHNITT"), "{name}");
            }
            Err(r) => {
                assert!(
                    !lean_kette,
                    "{name}: Rust refused ({r:?}) what Lean's chain accepts"
                );
            }
        }
    }
    // pw3, pe, q1, q1-nur-fold, q1-p57, q2, q2-ohne-prolog.
    assert_eq!(gebaut, 7);
}

