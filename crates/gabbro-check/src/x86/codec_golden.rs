/// One parsed golden line: either a canonical instruction's expected
/// bytes, or a decode refusal.
enum GoldenCase {
    Instr { befehl: Befehl, bytes: Vec<Byte> },
    Refuse { tag: String, bytes_hint: String },
}

fn reg(name: &str) -> Register {
    match name {
        "rax" => Register::Rax,
        "rcx" => Register::Rcx,
        "rdx" => Register::Rdx,
        "rbx" => Register::Rbx,
        "rsp" => Register::Rsp,
        "rbp" => Register::Rbp,
        "rsi" => Register::Rsi,
        "rdi" => Register::Rdi,
        "r8" => Register::R8,
        "r9" => Register::R9,
        "r10" => Register::R10,
        "r11" => Register::R11,
        "r12" => Register::R12,
        "r13" => Register::R13,
        "r14" => Register::R14,
        "r15" => Register::R15,
        other => panic!("unknown register in golden data: {other}"),
    }
}

fn cond(name: &str) -> Bedingung {
    match name {
        "o" => Bedingung::O,
        "no" => Bedingung::No,
        "b" => Bedingung::B,
        "ae" => Bedingung::Ae,
        "e" => Bedingung::E,
        "ne" => Bedingung::Ne,
        "be" => Bedingung::Be,
        "a" => Bedingung::A,
        "s" => Bedingung::S,
        "ns" => Bedingung::Ns,
        "p" => Bedingung::P,
        "np" => Bedingung::Np,
        "l" => Bedingung::L,
        "ge" => Bedingung::Ge,
        "le" => Bedingung::Le,
        "g" => Bedingung::G,
        other => panic!("unknown condition in golden data: {other}"),
    }
}

/// `ScalarFloat.lean`'s `intWort`, re-derived here only to turn a
/// PRE-WRAP golden immediate (the value the sweep asked for, before
/// Lean's own `intWort` wrapped it -- e.g. `2^63`) into the `u64` our
/// `Befehl::MovImm64` carries. This is the SAME formula as
/// `lower::int_wort`; duplicated rather than imported so this file
/// stays a standalone check of `codec.rs` against the golden text.
fn int_wort(n: i128) -> u64 {
    const MODULUS: i128 = 1i128 << 64;
    n.rem_euclid(MODULUS) as u64
}

fn hex_to_bytes(s: &str) -> Vec<Byte> {
    assert_eq!(s.len() % 2, 0, "odd hex length in golden data: {s}");
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).expect("valid hex byte in golden data"))
        .collect()
}

fn disp(v: i128) -> Disp32 {
    // Every displacement the sweep emits (0, 1, -1, i32::MAX, i32::MIN)
    // fits exactly in `i32`; this is not a general 32-bit wrap.
    Disp32::von_signed(i32::try_from(v).expect("golden displacement fits i32"))
}

fn parse_line(line: &str) -> GoldenCase {
    let parts: Vec<&str> = line.split(' ').collect();
    match parts[0] {
        "MOVIMM64" => {
            let dst = reg(parts[1]);
            let v: i128 = parts[2].parse().expect("golden immediate parses");
            let bytes = hex_to_bytes(parts[3]);
            GoldenCase::Instr {
                befehl: Befehl::MovImm64 {
                    dst,
                    value: int_wort(v),
                },
                bytes,
            }
        }
        "MOVREG64" => GoldenCase::Instr {
            befehl: Befehl::MovReg64 {
                dst: reg(parts[1]),
                src: reg(parts[2]),
            },
            bytes: hex_to_bytes(parts[3]),
        },
        "ADDREG64" => GoldenCase::Instr {
            befehl: Befehl::AddReg64 {
                dst: reg(parts[1]),
                src: reg(parts[2]),
            },
            bytes: hex_to_bytes(parts[3]),
        },
        "SUBREG64" => GoldenCase::Instr {
            befehl: Befehl::SubReg64 {
                dst: reg(parts[1]),
                src: reg(parts[2]),
            },
            bytes: hex_to_bytes(parts[3]),
        },
        "XORREG64" => GoldenCase::Instr {
            befehl: Befehl::XorReg64 {
                dst: reg(parts[1]),
                src: reg(parts[2]),
            },
            bytes: hex_to_bytes(parts[3]),
        },
        "CMPREG64" => GoldenCase::Instr {
            befehl: Befehl::CmpReg64 {
                lhs: reg(parts[1]),
                rhs: reg(parts[2]),
            },
            bytes: hex_to_bytes(parts[3]),
        },
        "LOAD64" => {
            let v: i128 = parts[3].parse().expect("golden displacement parses");
            GoldenCase::Instr {
                befehl: Befehl::Load64 {
                    dst: reg(parts[1]),
                    base: reg(parts[2]),
                    disp: disp(v),
                },
                bytes: hex_to_bytes(parts[4]),
            }
        }
        "STORE64" => {
            let v: i128 = parts[3].parse().expect("golden displacement parses");
            GoldenCase::Instr {
                befehl: Befehl::Store64 {
                    base: reg(parts[1]),
                    src: reg(parts[2]),
                    disp: disp(v),
                },
                bytes: hex_to_bytes(parts[4]),
            }
        }
        "JUMP32" => {
            let v: i128 = parts[1].parse().expect("golden displacement parses");
            GoldenCase::Instr {
                befehl: Befehl::Jump32 { disp: disp(v) },
                bytes: hex_to_bytes(parts[2]),
            }
        }
        "CALL32" => {
            let v: i128 = parts[1].parse().expect("golden displacement parses");
            GoldenCase::Instr {
                befehl: Befehl::Call32 { disp: disp(v) },
                bytes: hex_to_bytes(parts[2]),
            }
        }
        "JUMPIF32" => {
            let v: i128 = parts[2].parse().expect("golden displacement parses");
            GoldenCase::Instr {
                befehl: Befehl::JumpIf32 {
                    cond: cond(parts[1]),
                    disp: disp(v),
                },
                bytes: hex_to_bytes(parts[3]),
            }
        }
        "PUSH64" => GoldenCase::Instr {
            befehl: Befehl::Push64 { src: reg(parts[1]) },
            bytes: hex_to_bytes(parts[2]),
        },
        "POP64" => GoldenCase::Instr {
            befehl: Befehl::Pop64 { dst: reg(parts[1]) },
            bytes: hex_to_bytes(parts[2]),
        },
        "RET" => GoldenCase::Instr {
            befehl: Befehl::Ret,
            bytes: hex_to_bytes(parts[1]),
        },
        "REFUSE" => GoldenCase::Refuse {
            tag: parts[1].to_string(),
            bytes_hint: parts[2].to_string(),
        },
        other => panic!("unknown golden tag: {other}"),
    }
}

fn parsed_golden_lines() -> Vec<GoldenCase> {
    GOLDEN_DATA.lines().map(parse_line).collect()
}

#[cfg(test)]
mod proben {
    use super::*;

    /// Every golden instruction line: Rust `encode` reproduces the exact
    /// bytes Lean's `encode` printed, and `decode` on those bytes
    /// reproduces the exact instruction with the correct length.
    #[test]
    fn golden_instruktionen_stimmen_mit_lean_ueberein() {
        let cases = parsed_golden_lines();
        let mut instr_count = 0usize;
        for case in cases {
            match case {
                GoldenCase::Instr { befehl, bytes } => {
                    instr_count += 1;
                    let rust_bytes = encode(&befehl);
                    assert_eq!(
                        rust_bytes, bytes,
                        "encode({befehl:?}) diverges from Lean's bytes"
                    );
                    let d: Decodiert = decode(&bytes)
                        .unwrap_or_else(|| panic!("decode of Lean bytes for {befehl:?} refused"));
                    assert_eq!(d.befehl, befehl, "decode disagrees with the golden instruction");
                    assert_eq!(
                        d.laenge as usize,
                        bytes.len(),
                        "decoded length disagrees with the golden byte count"
                    );
                }
                GoldenCase::Refuse { .. } => {}
            }
        }
        assert_eq!(instr_count, 4043, "unexpected count of golden instruction lines");
    }

    /// Every golden refusal line: the exact bytes Lean's own `decode`
    /// (re-run via `#eval`, not `decide`) refused are refused here too.
    #[test]
    fn golden_abweisungen_stimmen_mit_lean_ueberein() {
        let refusal_bytes: Vec<Vec<Byte>> = vec![
            vec![],
            vec![0x48],
            vec![0xE9, 0x01],
            vec![0x0F],
            vec![0x41],
            vec![0xFF],
            vec![0x4A, 0x89, 0xC0],
            vec![0x89, 0xC0],
            vec![0x48, 0x89, 0x00],
            vec![0x48, 0x8B, 0xC0],
            vec![0x48, 0x8B, 0x84, 0x00, 0x00, 0x00, 0x00, 0x00],
            vec![0x48, 0x8B, 0x84, 0x24],
            vec![0xEB, 0x00],
            vec![0x66, 0xC3],
            vec![0x0F, 0x90, 0x00, 0x00, 0x00, 0x00],
        ];
        let mut count = 0usize;
        for case in parsed_golden_lines() {
            if let GoldenCase::Refuse { tag, bytes_hint } = case {
                assert_eq!(bytes_hint, "NONE", "unexpected non-refusal for {tag}");
                count += 1;
            }
        }
        assert_eq!(count, refusal_bytes.len(), "golden refusal count mismatch");
        for bytes in refusal_bytes {
            assert_eq!(decode(&bytes), None, "bytes {bytes:?} must be refused");
        }
    }
}
