body = []
for name, kind, src, want in cases:
    t = toks(src)
    if kind == 'pred':
        body.append(f'theorem {name} : predIs {t}\n    ({want}) = true := by decide')
    elif kind == 'predx':
        body.append(f'theorem {name} : predFails {t} = true := by decide')
    elif kind == 'expr':
        body.append(f'theorem {name} : exprIs {t}\n    ({want}) = true := by decide')
    elif kind == 'stmt':
        body.append(f'theorem {name} : stmtIs {t}\n    ({want}) = true := by decide')
    elif kind == 'stmtx':
        body.append(f'theorem {name} : stmtFails {t} = true := by decide')
    elif kind == 'item':
        body.append(f'theorem {name} : itemsOk {t} = true := by decide')
    elif kind == 'itemx':
        body.append(f'theorem {name} : itemsFail {t} = true := by decide')
open(W + 'Cover/Proben.lean', 'w').write(head + '\n\n'.join(body) + '\n\nend Gabbro.Grammatik.Parser.CoverProben\n')
